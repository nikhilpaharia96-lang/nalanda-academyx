// Snapshots lib/content/siteContent.ts into the API so the admin panel and
// the API know the exact shape (and default values) of every editable
// section. Run from the repo root:  npm run export:site-defaults
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { buildLocalSiteContent } from "../lib/content/siteContent";

// Deterministic output: never bake a developer's local env into the defaults.
for (const k of ["NEXT_PUBLIC_GOOGLE_MAPS_URL", "NEXT_PUBLIC_SOCIAL_INSTAGRAM", "NEXT_PUBLIC_SOCIAL_FACEBOOK", "NEXT_PUBLIC_SOCIAL_YOUTUBE"]) {
  delete process.env[k];
}

const content = JSON.parse(JSON.stringify(buildLocalSiteContent()));
const out = resolve(__dirname, "../../api/src/site-content/defaults.generated.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// AUTO-GENERATED by apps/public-site/scripts/export-site-defaults.ts — do not edit by hand.\n` +
    `// Run \`npm run export:site-defaults\` from the repo root to refresh.\n` +
    `/* eslint-disable */\n` +
    `export const SITE_CONTENT_DEFAULTS: Record<string, any> = ${JSON.stringify(content, null, 2)};\n`
);
console.log(`Wrote ${out} (${Object.keys(content).length} sections)`);
